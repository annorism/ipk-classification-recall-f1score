import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import recall_score, f1_score, classification_report

data = pd.read_csv("Hasil_IPK_Final (1).csv")

X = data[["JamBelajar", "Kehadiran", "Tugas"]]

y = data["IPK"].astype(str)

X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.3,
    random_state=42,
    stratify=y
)

model = DecisionTreeClassifier(random_state=42)

model.fit(X_train, y_train)

y_pred = model.predict(X_test)

print("Recall (Macro):", recall_score(y_test, y_pred, average="macro"))
print("F1-Score (Macro):", f1_score(y_test, y_pred, average="macro"))

print("\nClassification Report")
print(classification_report(y_test, y_pred))

data["Lulus"] = data["IPK"].apply(
    lambda x: "Ya" if x >= 2.75 else "Tidak"
)

print(data.head())

data.to_csv("Hasil_IPK_Status.csv", index=False)

import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.metrics import confusion_matrix

kelas = sorted(y.unique(), key=float)

cm = confusion_matrix(
    y_test,
    y_pred,
    labels=kelas
)

plt.figure(figsize=(8, 6))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=kelas,
    yticklabels=kelas
)

plt.title("Confusion Matrix - Prediksi Kategori IPK")
plt.xlabel("Prediksi IPK")
plt.ylabel("IPK Aktual")

plt.show()

importance = pd.DataFrame({
    "Fitur": X.columns,
    "Importance": model.feature_importances_
})

importance = importance.sort_values(
    by="Importance",
    ascending=False
)

plt.figure(figsize=(8, 5))

sns.barplot(
    data=importance,
    x="Importance",
    y="Fitur"
)

plt.title("Feature Importance - Decision Tree")
plt.xlabel("Tingkat Kepentingan")
plt.ylabel("Fitur")

plt.show()

